export function resolveLanguage(override: 'system' | 'en' | 'es'): 'en' | 'es' {
  if (override !== 'system') return override;
  return getLocales().find((locale) => locale.languageCode === 'es' || locale.languageCode === 'en')
    ?.languageCode === 'es'
    ? 'es'
    : 'en';
}
void i18n.use(initReactI18next).init({
  resources,
  lng: resolveLanguage('system'),
  fallbackLng: 'en',
  keySeparator: false,
  interpolation: { escapeValue: false },
});
export default i18n;
